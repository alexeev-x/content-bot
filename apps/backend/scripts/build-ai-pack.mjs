// Builds apps/backend/src/modules/ai/pack.generated.ts from docs/ai (the AI writer's only source, docs/ai/README.md),
// so the Worker bundle carries the pack, the lexicon and the examples. `--check` fails when the file is stale.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(import.meta.url), '../../../..');
const docs = join(root, 'docs/ai');
const out = join(root, 'apps/backend/src/modules/ai/pack.generated.ts');

const md = (name) => readFileSync(join(docs, 'pack', name), 'utf8').trim();
const jsonl = (path) =>
  readFileSync(join(docs, path), 'utf8')
    .split('\n')
    .filter((line) => line.trim() !== '')
    .map((line) => JSON.parse(line));

const pack = {
  core: md('core.md'),
  output: md('output.md'),
  lessons: md('lessons.md'),
  state: md('state.md'),
  formats: {
    fidit: md('format-uchu-fidit.md'),
    igrat: md('format-uchus-igrat.md'),
    standalone: md('format-standalone.md'),
    telegram: md('format-telegram.md')
  }
};
const lexicon = jsonl('lexicon.jsonl').map((row) => ({ w: row.w, m: row.m }));
const reels = jsonl('examples/reels.jsonl')
  .filter((row) => row.t && !row.t.startsWith('('))
  .map((row) => ({ id: row.id, f: row.f, r: row.r, title: row.title, t: row.t }));
const telegram = jsonl('examples/telegram.jsonl').map((row) => ({ k: row.k, t: row.t, ...(row.g ? { g: 1 } : {}) }));
const extra = readdirSync(join(docs, 'pack')).filter(
  (name) =>
    ![
      'core.md',
      'output.md',
      'lessons.md',
      'state.md',
      'format-uchu-fidit.md',
      'format-uchus-igrat.md',
      'format-standalone.md',
      'format-telegram.md'
    ].includes(name)
);
if (extra.length > 0) throw new Error(`docs/ai/pack has files the generator does not know: ${extra.join(', ')}`);

const text = `// GENERATED by apps/backend/scripts/build-ai-pack.mjs from docs/ai — do not edit; run \`npm run ai:pack\`.

export const AI_PACK = ${JSON.stringify(pack)} as const;
export const AI_LEXICON: readonly { w: readonly string[]; m: string }[] = ${JSON.stringify(lexicon)};
export const AI_REEL_EXAMPLES: readonly { id: string; f: 'fidit' | 'igrat' | 'solo'; r: 'g' | 'r' | 'a'; title: string; t: string }[] = ${JSON.stringify(reels)};
export const AI_TELEGRAM_EXAMPLES: readonly { k: string; t: string; g?: 1 }[] = ${JSON.stringify(telegram)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {}
  if (current !== text) {
    console.error('apps/backend/src/modules/ai/pack.generated.ts is out of date: run `npm run ai:pack`');
    process.exit(1);
  }
  console.log('ai pack: up to date');
} else {
  writeFileSync(out, text);
  console.log(`ai pack: wrote ${out} (${Math.round(text.length / 1024)} KB)`);
}
