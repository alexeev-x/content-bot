// The bank of 100 the owner approved on 29.10.2026, in a shuffled order without repeats.
export async function abilityInLife(context: RubricContext): Promise<RubricSample> {
  const turn = await context.sources.turns?.next('ability_in_life');
  const size = LIFE_BANK.length;
  const chosen =
    turn === undefined
      ? pick(LIFE_BANK, context.random)
      : (LIFE_BANK[shuffledOrder(Math.floor(turn / size), size)[turn % size] ?? 0] ?? pick(LIFE_BANK, context.random));
  return {
    picture: null,
    text: '',
    pictureInPoll: true,
    noPicture: true,
    ownText: true,
    poll: poll(chosen.question, [...chosen.options, chosen.joke])
  };
}

