export async function wouldYouRather(context: RubricContext): Promise<RubricSample> {
  const turn = await context.sources.turns?.next('would_you_rather');
  const size = RATHER_BANK.length;
  const chosen =
    turn === undefined
      ? pick(RATHER_BANK, context.random)
      : (RATHER_BANK[shuffledOrder(Math.floor(turn / size), size)[turn % size] ?? 0] ??
        pick(RATHER_BANK, context.random));
  return {
    picture: null,
    text: '',
    noPicture: true,
    ownText: true,
    poll: poll('Что выберешь?', shuffled(chosen, context.random))
  };
}

