const LEAFLET_FOOTER = '💊 — принимаю · 🤮 — у меня побочка';

function leafletRich(leaflet: Leaflet): string {
  const field = (line: string) => {
    const colon = line.indexOf(':');
    return colon > 0 && colon < 30
      ? `<p><b>${escapeHtml(line.slice(0, colon + 1))}</b>${escapeHtml(line.slice(colon + 1))}</p>`
      : `<p>${escapeHtml(line)}</p>`;
  };
  return [
    `<p><b>${escapeHtml(leaflet.item)}. Инструкция по применению</b></p>`,
    ...leaflet.lines.map(field),
    `<p>${escapeHtml(LEAFLET_FOOTER)}</p>`
  ].join('');
}

export function itemLeaflet(context: RubricContext): Promise<RubricSample> {
  const leaflet = pick(LEAFLETS, context.random);
  return Promise.resolve({
    picture: null,
    text: [`${leaflet.item}. Инструкция по применению`, ...leaflet.lines].join('\n'),
    rich: leafletRich(leaflet),
    footer: LEAFLET_FOOTER,
    boldLead: true,
    noPicture: true,
    ownText: true,
    poll: null
  });
}

