/** The nickname fits the 560 px column: Tektur capitals are about 0.64 em wide, 150 px at most (Баратрум ran into the hero). */
const nameSize = (name: string) => Math.min(150, Math.floor(540 / (Math.max([...name].length, 1) * 0.64)));

function cardPage(heroName: string, nickname: string, games: number): string {
  return picturePage(
    `<div class="left"><div class="title">Что брать рекруту</div><div class="name" style="font-size:${nameSize(nickname)}px">${escapeHtml(nickname)}</div>` +
      `<div class="stat"><div class="num">${games}</div><div class="cap">${gamesWord(games)} из 100<br>выигрывает<br><strong>на Рекрутах</strong></div>` +
      `<img class="medal" src="${rankMedalImage(RECRUIT_BRACKET)}" alt=""></div></div>` +
      `<img class="portrait" src="${heroImage(heroName)}" alt="">`,
    CARD_CSS
  );
}

export async function recruitPicks(context: RubricContext): Promise<RubricSample> {
  const [stats, heroes] = await Promise.all([
    needStats(context).heroBracketStats(RECRUIT_BRACKET),
    context.sources.heroes()
  ]);
  const idByName = new Map(heroes.map((hero) => [hero.name, hero.id]));
  const top = stats
    .filter((each) => each.matches >= RECRUIT_MIN_MATCHES)
    .map((each) => ({ heroId: each.heroId, winRate: each.wins / each.matches }))
    .sort((a, b) => b.winRate - a.winRate)
    .slice(0, RECRUIT_TOP);
  const candidates = RECRUIT_POSTS.flatMap((post) => {
    const found = top.find((each) => each.heroId === idByName.get(post.hero));
    return found === undefined ? [] : [{ post, winRate: found.winRate, first: found === top[0] }];
  });
  if (candidates.length === 0) throw noData('bank heroes among the Рекрут leaders');
  const { post, winRate, first } = pick(candidates, context.random);
  const games = Math.round(winRate * 100);
  const lines = post.lines.map((line) => {
    const counted = line.replace(/≈\d+ игр\S* из 100/u, `${games} ${gamesWord(games)} из 100`);
    // «— больше всех» stays only when the hero really tops the week on Рекрут.
    return first ? counted : counted.replace(' — больше всех.', '.');
  });
  const [heading = '', ...rest] = lines;
  const nickname = heading.replace(/^Что брать рекруту:\s*/u, '');
  return {
    picture: { html: cardPage(post.hero, nickname, games), ...PICTURE_SIZE },
    text: lines.join('\n'),
    rich: [`<p><b>${escapeHtml(heading)}</b></p>`, ...rest.map(fieldHtml), `<p>${escapeHtml(RECRUIT_FOOTER)}</p>`].join(
      ''
    ),
    footer: RECRUIT_FOOTER,
    boldLead: true,
    ownText: true,
    poll: null
  };
}
