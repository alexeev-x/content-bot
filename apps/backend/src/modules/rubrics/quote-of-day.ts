/** Reaction pairs by turns, so the posts don't all end the same. */
const REACTIONS = ['🗿 — база · 🤡 — кринж', '💯 — жиза · 🥴 — хуйня', '🫡 — уважаю · 💩 — говно'] as const;

export async function quoteOfDay(context: RubricContext): Promise<RubricSample> {
  const turn = await context.sources.turns?.next('quote_of_day');
  const size = QUOTES.length;
  const [quote, author] =
    turn === undefined
      ? pick(QUOTES, context.random)
      : (QUOTES[shuffledOrder(Math.floor(turn / size), size)[turn % size] ?? 0] ?? pick(QUOTES, context.random));
  const reactions =
    REACTIONS[(turn ?? Math.floor(context.random() * REACTIONS.length)) % REACTIONS.length] ?? REACTIONS[0];
  return {
    picture: null,
    text: `Цитата дня\n«${quote}»\n— ${author}\n\n${reactions}`,
    rich: `<p><b>Цитата дня</b></p><blockquote>«${escapeHtml(quote)}»<br>— ${escapeHtml(author)}</blockquote><p>${escapeHtml(reactions)}</p>`,
    boldLead: true,
    noPicture: true,
    ownText: true,
    poll: null
  };
}
