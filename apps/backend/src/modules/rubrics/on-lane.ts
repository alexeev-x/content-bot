// «Ты на линии» (owner, 30.10.2026): a Telegram quiz — a lane or skirmish moment, one mechanic with one right answer,
// three sensible options and a crude one, and why after the answer. Every number the text names comes from Valve's
// data at posting time (owner: «чтобы он автоматом подстроился»), and a «Ваншот или нет?» answer is worked out from
// those numbers, so a patch never leaves an old answer behind; a question whose value Valve no longer has is set aside
// and named in the owner's notes.

interface LaneQuiz {
  id: string;
  /** The numbers `{name}` stands for in the texts. */
  values?: Record<string, ValueRef>;
  /** Numbers worked out from `values` (a distance just outside a radius, a total), also usable as `{name}`. */
  calc?: (values: Values) => Values;
  setup: string;
  question: string;
  /** The right answer and one or two wrong ones; a «Ваншот» sets `kills` instead and gives yes/no here as right/wrong[0]. */
  right: string;
  wrong: readonly [string, string] | readonly [string];
  joke: string;
  /** «Ваншот или нет?»: true when the numbers kill — then `right` is «yes», else `wrong[0]` is the right one. */
  kills?: (values: Values) => boolean;
  explanation: string | ((values: Values, kills: boolean) => string);
}

