const POSITION_WORDS = ['первая', 'вторая', 'третья', 'четвёртая', 'пятая'];
const spaced = (value: number) =>
  Math.round(value)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, ' ');

const keyOf = (keys: Keys, id: number) => keys.get(id) ?? '';
/** The earliest purchase of any of the items, [id, minute]; purchases before the clock starts do not count. */
const firstBought = (game: ShameGame, keys: Keys, wanted: readonly string[]) =>
  game.purchases
    .filter(([id, minute]) => wanted.includes(keyOf(keys, id)) && minute >= 0)
    .sort((a, b) => a[1] - b[1])[0];
const finalKeys = (game: ShameGame, keys: Keys) => game.items.map((id) => keyOf(keys, id));

function medianOf(medians: readonly Medians[], position: number): Medians {
  return (
    medians.find((each) => each.position === position) ?? { position, deaths: 6, kills: 5, assists: 8, nw20: null }
  );
}

function deathsEvidence(game: ShameGame, medians: readonly Medians[]): Evidence {
  const usual = Math.round(medianOf(medians, game.position).deaths);
  return { kind: 'deaths', fact: `Смертей — ${game.deaths}, а на этой позиции обычно ${usual}.`, items: [] };
}

/** Up to two pieces of evidence of a bad game, by fixed priority; none found, the deaths against the usual. */
export function scoreEvidence(game: ShameGame, keys: Keys, medians: readonly Medians[]): Evidence[] {
  const found: Evidence[] = [];
  const { position } = game;
  const mate = game.allyNw20.find((each) => each.position === 5);
  if (position <= 2 && game.nw20 !== null && mate !== undefined && game.nw20 < mate.nw20)
    found.push({
      kind: 'networth',
      fact: `Нетворс на 20-й — ${spaced(game.nw20)}. У пятёрки — ${spaced(mate.nw20)}.`,
      items: []
    });
  if (position <= 3 && game.damage !== null && game.damages.length === 10 && game.damage === Math.min(...game.damages))
    found.push({ kind: 'damage', fact: `Урона меньше всех из десяти — ${spaced(game.damage)}.`, items: [] });
  const midas = firstBought(game, keys, ['hand_of_midas']);
  if (midas !== undefined && midas[1] >= 25)
    found.push({
      kind: 'midas',
      fact: `Мидас на ${midas[1]}-й минуте.`,
      items: [{ key: 'hand_of_midas', minute: midas[1] }]
    });
  const rapier = firstBought(game, keys, ['rapier']);
  if (rapier !== undefined)
    found.push({
      kind: 'rapier',
      fact: `Рапира на ${rapier[1]}-й минуте — и игра проиграна.`,
      items: [{ key: 'rapier', minute: rapier[1] }]
    });
  const boots = firstBought(game, keys, BOOTS);
  if (position <= 3 && boots !== undefined && boots[1] > 12)
    found.push({ kind: 'boots', fact: `Сапоги только на ${boots[1]}-й минуте.`, items: [] });
  const bkb = firstBought(game, keys, ['black_king_bar']);
  if (bkb !== undefined && bkb[1] > 35)
    found.push({ kind: 'bkb', fact: `БКБ на ${bkb[1]}-й минуте.`, items: [{ key: 'black_king_bar', minute: bkb[1] }] });
  const dagger = firstBought(game, keys, ['blink']);
  if (position >= 3 && dagger !== undefined && dagger[1] > 25)
    found.push({
      kind: 'dagger',
      fact: `Блинк на ${dagger[1]}-й минуте.`,
      items: [{ key: 'blink', minute: dagger[1] }]
    });
  return found.length === 0 ? [deathsEvidence(game, medians)] : found.slice(0, 2);
}

/** The shame score of a lost game: deaths twice as heavy, against the position's medians, per 40 minutes of play. */
export function shameScore(game: ShameGame, medians: readonly Medians[], hasEvidence: boolean): number {
  const median = medianOf(medians, game.position);
  const play =
    (2 * (game.deaths - median.deaths) - (game.kills - median.kills) - 0.5 * (game.assists - median.assists)) *
    (40 / game.minutes);
  const farm =
    game.nw20 !== null && median.nw20 !== null && median.nw20 > 0 ? 10 * Math.max(0, 1 - game.nw20 / median.nw20) : 0;
  return play + farm + (game.lane === -1 ? 3 : 0) + (hasEvidence ? 2 : 0);
}

/** The worst game by score; a tie goes to more deaths, then the longer game. */
export function worstByScore(games: readonly ShameGame[], medians: readonly Medians[], keys: Keys): Winner | null {
  const ranked = games.map((game): Winner => {
    const evidence = scoreEvidence(game, keys, medians);
    return {
      game,
      score: shameScore(
        game,
        medians,
        evidence.some((each) => each.kind !== 'deaths')
      ),
      evidence
    };
  });
  ranked.sort((a, b) => b.score - a.score || b.game.deaths - a.game.deaths || b.game.minutes - a.game.minutes);
  return ranked[0] ?? null;
}

