/** The full final build: the six slots and the neutral item, each with its purchase minute; evidence items marked. */
export function buildIcons(game: ShameGame, keys: Keys, evidence: readonly Evidence[]): BuildIcon[] {
  const marked = new Set(evidence.flatMap((each) => each.items.map((item) => item.key)));
  return [...game.items.slice(0, 6), ...(game.neutral === null ? [] : [game.neutral])].flatMap((id) => {
    const key = keyOf(keys, id);
    return key === '' ? [] : [{ key, minute: firstBought(game, keys, [key])?.[1] ?? null, evidence: marked.has(key) }];
  });
}

/** The absurdity of a build by a rule table: each rule that applies adds its points and one piece of evidence. */
export function buildAbsurdity(game: ShameGame, keys: Keys): { score: number; evidence: Evidence[] } {
  const final = finalKeys(game, keys);
  const icon = (key: string) => ({ key, minute: firstBought(game, keys, [key])?.[1] ?? null });
  const names = (list: string[]) => list.map((key) => ITEM_RU[key] ?? key).join(', ');
  const hits: { points: number; item: Evidence }[] = [];
  const support = final.filter((key) => SUPPORT_ITEMS.includes(key));
  if (game.position <= 3 && support.length >= 2)
    hits.push({
      points: 3 * support.length,
      item: { kind: 'support_items', fact: `Керри собрал саппорта: ${names(support)}.`, items: support.map(icon) }
    });
  const carry = final.filter((key) => CARRY_ITEMS.includes(key));
  if (game.position >= 4 && carry.length >= 1)
    hits.push({
      points: 5 * carry.length,
      item: { kind: 'carry_items', fact: `Саппорт собрал керри: ${names(carry)}.`, items: carry.map(icon) }
    });
  const rapiers = game.purchases.filter(([id]) => keyOf(keys, id) === 'rapier');
  if (rapiers.length >= 2)
    hits.push({
      points: 6,
      item: {
        kind: 'two_rapiers',
        fact: `Рапир куплено ${rapiers.length}, игра проиграна.`,
        items: rapiers.slice(0, 2).map(([, minute]) => ({ key: 'rapier', minute }))
      }
    });
  const hasBoots = final.some((key) => BOOTS.includes(key)) || firstBought(game, keys, BOOTS) !== undefined;
  if (!hasBoots && game.minutes >= 25)
    hits.push({
      points: 4,
      item: { kind: 'no_boots', fact: `Игра ${game.minutes} минут, а сапог так и не было.`, items: [] }
    });
  if (game.position === 5 && final.includes('hand_of_midas') && final.includes('ultimate_scepter'))
    hits.push({
      points: 5,
      item: {
        kind: 'midas_aghs',
        fact: 'Пятая позиция: Мидас и Аганим.',
        items: ['hand_of_midas', 'ultimate_scepter'].map(icon)
      }
    });
  hits.sort((a, b) => b.points - a.points);
  return {
    score: hits.reduce((sum, each) => sum + each.points, 0),
    evidence: hits.slice(0, 2).map((each) => each.item)
  };
}

/** The most absurd build; fewer than `ABSURD_MIN` points is no absurdity. Ties go to the longer game. */
export function worstBuild(games: readonly ShameGame[], keys: Keys): Winner | null {
  const ranked = games
    .map((game): Winner => ({ game, ...buildAbsurdity(game, keys) }))
    .filter((each) => each.score >= ABSURD_MIN);
  ranked.sort((a, b) => b.score - a.score || b.game.minutes - a.game.minutes);
  return ranked[0] ?? null;
}

