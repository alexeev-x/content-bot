export function shameText(input: {
  dayMatches: number;
  hero: string;
  game: ShameGame;
  evidence: Evidence[];
  kind: 'score' | 'build';
  random: () => number;
}): string {
  const { game, evidence } = input;
  const lines = evidence.map((each) => each.fact);
  if (lines.length < 2) lines.push(pick(SHAME_JOKES[evidence[0]?.kind ?? 'deaths'], input.random));
  const bank = FEED_LINES[game.position as 1 | 2 | 3 | 4 | 5];
  const feed = bank === undefined ? undefined : pick(bank, input.random);
  return [
    input.kind === 'build' ? '🏆 Пидорок дня — сборка' : '🏆 Пидорок дня',
    pick(INTRO_LINES, input.random),
    `${input.hero}, ${POSITION_WORDS[game.position - 1] ?? ''} позиция: ${game.kills}/${game.deaths}/${game.assists} за ${game.minutes} ${plural(game.minutes, 'минуту', 'минуты', 'минут')}.`,
    ...lines.slice(0, 2),
    ...(feed === undefined ? [] : [feed]),
    pick(QUESTION_LINES, input.random),
    '🤡 — пидорок / 🫡 — уважаю'
  ].join('\n');
}

export async function shameOfDay(context: RubricContext): Promise<RubricSample> {
  const base = context.sources.heroMatches ?? null;
  const what = 'yesterday’s games in the stats base';
  if (base === null) throw noData(what);
  // Yesterday is the Moscow day before today's (RUBRICS_SCHEDULER.md, 29; it was the UTC day).
  const until = mskDayStart(context.now);
  const since = until - DAY_MS;
  const [heroes, items] = await Promise.all([context.sources.heroes(), context.sources.items()]);
  const itemNames = await context.sources.itemNames?.();
  const keys = new Map(items.map((item) => [item.id, item.key]));
  const turn = await context.sources.turns?.next('shame_of_day', 2);
  const first: 'score' | 'build' = (turn ?? Math.floor(context.random() * 2)) % 2 === 0 ? 'score' : 'build';

  const recent = new Set((await context.sources.shameHeroes?.used()) ?? []);
  const day = await base.worstGames(since, until, CANDIDATES);
  const wide = await base.worstGames(since, until, BUILD_ROWS, true);
  // The next best game of another hero: nobody twice within the last three winners.
  const fresh = (games: ShameGame[]) => games.filter((each) => !recent.has(each.heroId));
  const dayMatches = Math.max(day.dayMatches, wide.dayMatches);
  const order = first === 'score' ? (['score', 'build'] as const) : (['build', 'score'] as const);
  for (const kind of order) {
    const found =
      kind === 'score' ? worstByScore(fresh(day.games), day.medians, keys) : worstBuild(fresh(wide.games), keys);
    const hero = found === null ? undefined : heroes.find((each) => each.id === found.game.heroId);
    if (found === null || hero === undefined) continue;
    const spoken = spokenHeroName(hero.name.replace(/^npc_dota_hero_/, '')) ?? hero.localizedName;
    await context.sources.shameHeroes?.remember(found.game.heroId);
    return {
      facts: { shameHero: found.game.heroId, heroIds: [found.game.heroId], variant: kind },
      picture: shamePicture({
        heroName: hero.name,
        game: found.game,
        evidence: found.evidence,
        build: buildIcons(found.game, keys, found.evidence),
        kind,
        itemNames
      }),
      text: shameText({
        dayMatches,
        hero: spoken,
        game: found.game,
        evidence: found.evidence,
        kind,
        random: context.random
      }),
      ownText: true,
      poll: null
    };
  }
  throw noData(what);
}
