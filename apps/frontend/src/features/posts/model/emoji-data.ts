/** Words to search by: the emoji's own and its category's. */
export function searchEmoji(query: string): EmojiEntry[] {
  const needle = query.trim().toLowerCase().replaceAll('ё', 'е');
  if (needle === '') return [];
  return EMOJI_CATEGORIES.flatMap((category) => category.items).filter((item) =>
    item.words.replaceAll('ё', 'е').includes(needle)
  );
}

const RECENT_KEY = 'alexeev.emoji.recent';
const RECENT_MAX = 16;

/** Recently inserted emoji, this browser only; an unavailable storage reads as none. */
export function readRecentEmoji(): string[] {
  try {
    const raw: unknown = JSON.parse(localStorage.getItem(RECENT_KEY) ?? '[]');
    return Array.isArray(raw)
      ? raw.filter((item): item is string => typeof item === 'string').slice(0, RECENT_MAX)
      : [];
  } catch {
    return [];
  }
}

export function rememberEmoji(char: string): void {
  try {
    const next = [char, ...readRecentEmoji().filter((item) => item !== char)].slice(0, RECENT_MAX);
    localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch {
    // A private window or blocked storage: the picker still works, it just does not remember.
  }
}
